-- dev-veteran: a 4,000-word Russian library as MOCK CARD DATA (2026-08-05).
--
-- THREE constraints set this design, none of them negotiable:
--
--  1. NO writes to translations_cache. It is the shared dictionary real users'
--     searches read from; seeding 4,000 synthetic rows there would put invented
--     entries into real search results. (Casey, explicit.)
--  2. NO Azure translator calls. The fixture must build offline and for free.
--  3. cards has a UNIQUE INDEX on (deck_id, translation_id, coalesce(custom_back,'')).
--     This is the one that killed the previous attempt: it is an INDEX, not a
--     table constraint, so it does not appear in pg_constraint. Cycling one
--     translation_id across many cards in a single deck is impossible.
--
-- The resolution comes from the read path. mappers.mapWordListItem resolves
--     searchTarget = card.custom_back  ?? tr.translation
--     searchNative = card.custom_front ?? tr.display_source
-- so a card RENDERS its own custom_front/custom_back regardless of which
-- translations_cache row it points at. Every card therefore anchors to one real
-- ru translation and carries its own mocked pair -- and because custom_back is
-- part of the unique index, 4,000 distinct Russian words are 4,000 legal cards
-- in ONE deck. No dictionary pollution, no API, no fake decks.
--
-- WHERE THE WORDS COME FROM (both sides are real, the PAIRING is the mock):
--   target: the 4,000 most frequent Russian words, wordfreq's ru corpus,
--           Cyrillic-only and length >= 3 so the list is vocabulary rather than
--           prepositions.
--   native: the Wiktionary-derived Russian->WordNet mapping shipped in NLTK's
--           extended_omw (wn-wikt-rus.tab), resolved to an English lemma.
-- Generated once, offline, and frozen here. A handful of high-frequency function
-- words gloss oddly (для -> grist) because WordNet models content words; the
-- long tail is sound (проснуться -> wake up). Good enough for a fixture whose
-- job is scale, not lexicography.
--
-- dev_seed_words is a DEV FIXTURE TABLE and deliberately not translations_cache:
-- nothing in the app reads it, no lookup can ever surface it, and dropping it
-- costs nothing.
